import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

import {
  NO_LICENSE_FILE,
  bundledPackages,
  checkOutputs,
  collectNotices,
  pickLicenseFile,
  renderNotices,
} from './build-viewer.mjs';

const meta = (...paths) => ({ inputs: Object.fromEntries(paths.map((p) => [p, {}])) });

test('bundledPackages: plain, scoped, nested, deduped, sorted', () => {
  const m = meta(
    'src/viewer/ui/main.jsx',
    'node_modules/react/index.js',
    'node_modules/react/cjs/react.js',
    'node_modules/@scope/pkg/lib/a.js',
    'node_modules/a/node_modules/b/index.js',
  );
  assert.deepEqual(bundledPackages(m), [
    { name: '@scope/pkg', dir: 'node_modules/@scope/pkg' },
    { name: 'b', dir: 'node_modules/a/node_modules/b' },
    { name: 'react', dir: 'node_modules/react' },
  ]);
});

test('bundledPackages: strips a (disabled): prefix', () => {
  assert.deepEqual(bundledPackages(meta('(disabled):node_modules/p/off.js')), [
    { name: 'p', dir: 'node_modules/p' },
  ]);
});

test('pickLicenseFile', () => {
  assert.equal(pickLicenseFile(['index.js', 'LICENSE']), 'LICENSE');
  assert.equal(pickLicenseFile(['index.js', 'LICENSE-MIT.txt']), 'LICENSE-MIT.txt');
  assert.equal(pickLicenseFile(['license.md', 'package.json']), 'license.md');
  assert.equal(pickLicenseFile(['LICENSE', 'LICENSE-MIT']), 'LICENSE');
  assert.equal(pickLicenseFile(['LICENSE-MIT', 'LICENSE']), 'LICENSE');
  assert.equal(pickLicenseFile(['index.js']), null);
});

const io = (pkg, files, text = '') => ({
  readPackageJson: () => pkg,
  listFiles: () => files,
  readText: () => text,
});
const foo = [{ name: 'foo', dir: 'node_modules/foo' }];

test('collectNotices: clean package', () => {
  const { entries, problems } = collectNotices(
    foo,
    io({ version: '1.2.3', license: 'MIT' }, ['LICENSE'], 'Copyright (c) A\n\nBody\n'),
  );
  assert.deepEqual(problems, []);
  assert.deepEqual(entries, [
    { name: 'foo', version: '1.2.3', license: 'MIT', copyright: 'Copyright (c) A', text: 'Copyright (c) A\n\nBody', note: null },
  ]);
});

test('collectNotices: disallowed license', () => {
  const { entries, problems } = collectNotices(foo, io({ version: '1', license: 'GPL-3.0' }, ['LICENSE'], 'x'));
  assert.equal(entries.length, 0);
  assert.match(problems[0], /foo.*GPL-3\.0/);
});

test('collectNotices: license given as an object', () => {
  const { problems } = collectNotices(foo, io({ version: '1', license: { type: 'MIT' } }, ['LICENSE'], 'x'));
  assert.equal(problems.length, 1);
  assert.match(problems[0], /foo/);
});

test('collectNotices: no license file and not in the table', () => {
  const { problems } = collectNotices(foo, io({ version: '1', license: 'MIT' }, ['index.js']));
  assert.equal(problems.length, 1);
  assert.match(problems[0], /foo.*no license file.*NO_LICENSE_FILE/);
});

test('collectNotices: no license file but in the table', () => {
  const { entries, problems } = collectNotices(
    [{ name: 'bezier-js', dir: 'node_modules/bezier-js' }],
    io({ version: '6.1.4', license: 'MIT' }, ['index.js']),
  );
  assert.deepEqual(problems, []);
  assert.equal(entries[0].copyright, 'Copyright (c) Pomax');
  assert.equal(entries[0].text, NO_LICENSE_FILE['bezier-js'].text);
  assert.match(entries[0].note, /ships no license file/);
});

test('collectNotices: CRLF, trailing space and blank edges are normalized', () => {
  const { entries } = collectNotices(
    foo,
    io({ version: '1', license: 'ISC' }, ['LICENSE'], '\r\n\r\n  Copyright (c) B  \r\nline \r\n\r\n'),
  );
  assert.equal(entries[0].text, '  Copyright (c) B\nline');
  assert.equal(entries[0].copyright, 'Copyright (c) B');
});

const entry = (o) => ({ version: '1.0.0', license: 'MIT', copyright: null, note: null, ...o });

test('renderNotices: exact output, sorted by name', () => {
  const out = renderNotices([
    entry({ name: 'b', note: 'Careful.', text: 'B text' }),
    entry({ name: 'a', copyright: 'Copyright (c) A', text: 'Copyright (c) A\nA text' }),
  ]);
  assert.equal(
    out,
    [
      '# Third-Party Notices',
      '',
      "These libraries are bundled into `viewer.js`, the wiki viewer's client bundle. This file is generated by `scripts/build-viewer.mjs`; do not edit it by hand.",
      '',
      '## a 1.0.0',
      '',
      '- Source: `a` npm package, bundled by esbuild',
      '- License: MIT',
      '- Copyright (c) A',
      '',
      '```',
      'Copyright (c) A',
      'A text',
      '```',
      '',
      '## b 1.0.0',
      '',
      '- Source: `b` npm package, bundled by esbuild',
      '- License: MIT',
      '',
      'Careful.',
      '',
      '```',
      'B text',
      '```',
      '',
    ].join('\n'),
  );
});

test('renderNotices: four-backtick fence when text has a fence line', () => {
  const out = renderNotices([entry({ name: 'a', text: 'x\n```\ny' })]);
  assert.match(out, /\n````\nx\n```\ny\n````\n$/);
});

test('renderNotices: ends with exactly one newline', () => {
  const out = renderNotices([entry({ name: 'a', text: 'x' })]);
  assert.ok(out.endsWith('```\n') && !out.endsWith('\n\n'));
});

test('checkOutputs', () => {
  checkOutputs([{ path: '/r/viewer.js' }], '/r/viewer.js');
  assert.throws(() => checkOutputs([{ path: '/r/viewer.js' }, { path: '/r/x.css' }], '/r/viewer.js'), /unexpected/);
  assert.throws(() => checkOutputs([{ path: '/r/other.js' }], '/r/viewer.js'), /unexpected/);
});

