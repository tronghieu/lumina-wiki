#!/usr/bin/env node
/**
 * Builds the wiki viewer bundle (src/viewer/app/viewer.js) and its generated
 * THIRD-PARTY-NOTICES.md with esbuild.
 *
 * Writes nothing unless the bundle has a single output and every bundled
 * package has an allowed license and a license text.
 */

import { readFileSync, readdirSync, realpathSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { atomicWrite } from '../src/installer/fs.js';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const OUTFILE = 'src/viewer/app/viewer.js';
const NOTICES = 'src/viewer/app/THIRD-PARTY-NOTICES.md';
const ALLOWED_LICENSES = ['MIT', 'ISC', 'Apache-2.0', 'BSD-2-Clause', 'BSD-3-Clause'];

// Packages that publish no license file. Each entry needs a reviewed license text.
